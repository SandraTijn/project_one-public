    def __cmd(self, command):
        self.__i2c.write_byte_data(self.__oled_addr, 0x00, command)
    
    def __dat(self, data):
        self.__i2c.write_byte_data(self.__oled_addr, 0x40, data)
    

    def setup(self):
        self.__i2c = smbus.SMBus(self.__SMBus)

        for c in [
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00,
        0x40, 0xA1, 0xC8, 0xDA, 0x12, 0x81, 0x7F,
        0xA4, 0xA6, 0x8D, 0x14, 0xAF]:
            self.__cmd(c)
    
    def clear_screen(self):
        for page in range(8):
            self.__cmd(0xB0 + page)
            self.__cmd(0x00)
            self.__cmd(0x10)
            for _ in range(128):
                self.__dat(0x00)

    def draw_letter(self, x, page, pattern):
        self.__cmd(0xB0 + page)
        self.__cmd(0x00 + (x & 0x0F))
        self.__cmd(0x10 + (x >> 4))
        for b in pattern:
            self.__dat(b)

    # Tekst schrijven
    def draw_text(self, x, page, text):
        for char in text:
            pattern = self.__font5x8.get(char.upper(), self.__font5x8[' '])
            self.draw_letter(x, page, pattern)
            x += 6  # 5 pixels + 1 spatie
    

    def draw_bigger_text(self, x, page, text):
        for char in text:
            patterns = self.__bigger_font.get(char.upper(), self.__bigger_font[' '])
            # Draw top 8 rows (upper page)
            self.__cmd(0xB0 + page)
            self.__cmd(0x00 + (x & 0x0F))
            self.__cmd(0x10 + (x >> 4))
            for b in patterns[0]:
                self.__dat(b)
            # Draw bottom 8 rows (lower page)
            self.__cmd(0xB0 + page + 1)
            self.__cmd(0x00 + (x & 0x0F))
            self.__cmd(0x10 + (x >> 4))
            for b in patterns[1]:
                self.__dat(b)
            x += 11  # 10 pixels + 1 space

        
